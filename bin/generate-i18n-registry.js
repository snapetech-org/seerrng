#!/usr/bin/env node
/* eslint-disable @typescript-eslint/no-require-imports, no-console */
const fs = require('node:fs');
const path = require('node:path');

const root = path.resolve(__dirname, '..');
const config = JSON.parse(
  fs.readFileSync(path.join(root, 'config/i18n/locales.json'), 'utf8')
);
const byTag = new Map();
const clientFiles = new Set();
const serverFiles = new Set();

if (config.schemaVersion !== 1 || !Array.isArray(config.locales))
  throw new Error('Invalid locale registry schema.');

for (const locale of config.locales) {
  if (!/^[a-z]{2,3}(?:-[A-Z][a-z]{3})?(?:-[A-Z]{2}|-[0-9]{3})?$/.test(locale.tag))
    throw new Error(`Invalid canonical locale tag: ${locale.tag}`);
  if (byTag.has(locale.tag)) throw new Error(`Duplicate locale: ${locale.tag}`);
  if (clientFiles.has(locale.clientFile))
    throw new Error(`Client catalog reused: ${locale.clientFile}`);
  if (serverFiles.has(locale.serverFile))
    throw new Error(`Server catalog reused: ${locale.serverFile}`);
  if (!['ltr', 'rtl'].includes(locale.direction) || !locale.nativeName?.trim())
    throw new Error(`Invalid metadata for ${locale.tag}`);
  if (!['source', 'unreviewed'].includes(locale.reviewStatus))
    throw new Error(`Invalid review status for ${locale.tag}`);
  if (!fs.existsSync(path.join(root, 'src/i18n/locale', locale.clientFile)))
    throw new Error(`Missing client catalog for ${locale.tag}`);
  if (!fs.existsSync(path.join(root, 'server/i18n/locale', locale.serverFile)))
    throw new Error(`Missing server catalog for ${locale.tag}`);
  clientFiles.add(locale.clientFile);
  serverFiles.add(locale.serverFile);
  byTag.set(locale.tag, locale);
}

if (!byTag.has(config.baseLocale))
  throw new Error(`Base locale ${config.baseLocale} is not registered.`);
for (const locale of config.locales) {
  if (locale.tag === config.baseLocale && locale.fallback)
    throw new Error('The base locale cannot have a fallback.');
  if (locale.fallback && !byTag.has(locale.fallback))
    throw new Error(`Unknown fallback ${locale.fallback} for ${locale.tag}`);
  const seen = new Set([locale.tag]);
  let parent = locale.fallback;
  while (parent) {
    if (seen.has(parent)) throw new Error(`Fallback cycle at ${locale.tag}`);
    seen.add(parent);
    parent = byTag.get(parent)?.fallback;
  }
}

const quoteTs = (value) =>
  "'" +
  value
    .replaceAll("\\", "\\\\")
    .replaceAll("'", "\\'")
    .replaceAll("\n", "\\n") +
  "'";
const metadata = config.locales
  .map((locale) => {
    const fields = [
      "    tag: " + quoteTs(locale.tag) + ",",
      "    nativeName: " + quoteTs(locale.nativeName) + ",",
      "    direction: " + quoteTs(locale.direction) + ",",
      "    clientFile: " + quoteTs(locale.clientFile) + ",",
      "    serverFile: " + quoteTs(locale.serverFile) + ",",
      "    reviewStatus: " + quoteTs(locale.reviewStatus) + ",",
    ];
    if (locale.fallback)
      fields.push("    fallback: " + quoteTs(locale.fallback) + ",");
    return ["  {", ...fields, "  },"].join("\n");
  })
  .join("\n");

const baseLocale = quoteTs(config.baseLocale);
const languagesSource = [
  "// Generated by bin/generate-i18n-registry.js from config/i18n/locales.json.",
  "export type LocaleDefinition = {",
  "  tag: string;",
  "  nativeName: string;",
  "  direction: 'ltr' | 'rtl';",
  "  clientFile: string;",
  "  serverFile: string;",
  "  reviewStatus: 'source' | 'unreviewed';",
  "  fallback?: string;",
  "};",
  "",
  "export const localeRegistry = [",
  metadata,
  "] as const satisfies readonly LocaleDefinition[];",
  "",
  "export type AvailableLocale = (typeof localeRegistry)[number]['tag'];",
  "export const availableLocales = localeRegistry.map(",
  "  ({ tag }) => tag",
  ") as AvailableLocale[];",
  "export const localeCatalogFiles = Object.fromEntries(",
  "  localeRegistry.map(({ tag, serverFile }) => [tag, serverFile])",
  ") as Record<AvailableLocale, string>;",
  "",
  "export const isAvailableLocale = (value: unknown): value is AvailableLocale =>",
  "  typeof value === 'string' &&",
  "  localeRegistry.some(({ tag }) => tag === value);",
  "",
  "export const getLocaleMetadata = (value: string): LocaleDefinition => {",
  "  const exact = localeRegistry.find(",
  "    ({ tag }) => tag.toLowerCase() === value.toLowerCase()",
  "  );",
  "  if (exact) return exact;",
  "  const base = value.split(/[-_]/, 1)[0].toLowerCase();",
  "  return (",
  "    localeRegistry.find(({ tag }) => tag.toLowerCase() === base) ??",
  "    localeRegistry.find(({ tag }) => tag === " + baseLocale + ")!",
  "  );",
  "};",
  "",
  "export const getLocaleFallbackChain = (",
  "  value: AvailableLocale",
  "): AvailableLocale[] => {",
  "  const chain: AvailableLocale[] = [];",
  "  const seen = new Set<string>();",
  "  let current: string = value;",
  "  while (!seen.has(current)) {",
  "    seen.add(current);",
  "    const locale = localeRegistry.find(",
  "      ({ tag }) => tag === current",
  "    ) as LocaleDefinition | undefined;",
  "    if (!locale) break;",
  "    chain.push(locale.tag as AvailableLocale);",
  "    if (locale.tag === " + baseLocale + ") break;",
  "    current = locale.fallback ?? " + baseLocale + ";",
  "  }",
  "  if (chain.at(-1) !== " + baseLocale + ") chain.push(" + baseLocale + " as AvailableLocale);",
  "  return chain;",
  "};",
  "",
  "export const resolveAcceptLanguage = (",
  "  header?: string | string[] | null,",
  "  cookieLocale?: string | null",
  "): AvailableLocale => {",
  "  if (cookieLocale && isAvailableLocale(cookieLocale)) return cookieLocale;",
  "  const value = Array.isArray(header) ? header.join(',') : header ?? '';",
  "  const preferences = value",
  "    .split(',')",
  "    .map((part, index) => {",
  "      const [rawTag, ...parameters] = part.trim().split(';');",
  "      const rawQuality = parameters.find((parameter) =>",
  "        parameter.trim().startsWith('q=')",
  "      );",
  "      const quality = rawQuality ? Number(rawQuality.trim().slice(2)) : 1;",
  "      return { tag: rawTag, quality, index };",
  "    })",
  "    .filter(",
  "      ({ tag, quality }) =>",
  "        tag &&",
  "        tag !== '*' &&",
  "        Number.isFinite(quality) &&",
  "        quality > 0 &&",
  "        quality <= 1",
  "    )",
  "    .sort(",
  "      (left, right) =>",
  "        right.quality - left.quality || left.index - right.index",
  "    );",
  "",
  "  for (const preference of preferences) {",
  "    let canonical = preference.tag;",
  "    try {",
  "      canonical = Intl.getCanonicalLocales(preference.tag)[0];",
  "    } catch {",
  "      continue;",
  "    }",
  "    const exact = localeRegistry.find(",
  "      ({ tag }) => tag.toLowerCase() === canonical.toLowerCase()",
  "    );",
  "    if (exact) return exact.tag as AvailableLocale;",
  "    const language = canonical.split('-', 1)[0].toLowerCase();",
  "    const match = localeRegistry.find(",
  "      ({ tag }) => tag.toLowerCase() === language",
  "    );",
  "    const regionalMatch = localeRegistry.find(",
  "      ({ tag }) => tag.toLowerCase().split('-', 1)[0] === language",
  "    );",
  "    if (match || regionalMatch)",
  "      return (match ?? regionalMatch)!.tag as AvailableLocale;",
  "  }",
  "  return " + baseLocale + " as AvailableLocale;",
  "};",
  "",
].join("\n");
const loaders = config.locales
  .map(({ tag, clientFile }) => {
    const key = /^[A-Za-z_$][A-Za-z0-9_$]*$/.test(tag) ? tag : quoteTs(tag);
    return "  " + key + ": () => import('./" + clientFile + "'),";
  })
  .join("\n");
const clientSource = [
  "// Generated by bin/generate-i18n-registry.js from config/i18n/locales.json.",
  "import {",
  "  getLocaleFallbackChain,",
  "  type AvailableLocale,",
  "} from '@server/types/languages';",
  "",
  "type MessageCatalog = Record<string, string>;",
  "const catalogLoaders = {",
  loaders,
  "} satisfies Record<",
  "  AvailableLocale,",
  "  () => Promise<{ default: MessageCatalog }>",
  ">;",
  "",
  "export const loadLocaleMessages = async (",
  "  locale: AvailableLocale",
  "): Promise<MessageCatalog> => {",
  "  const chain = getLocaleFallbackChain(locale).reverse();",
  "  const resolved: MessageCatalog = {};",
  "  for (const fallback of chain) {",
  "    Object.assign(resolved, (await catalogLoaders[fallback]()).default);",
  "  }",
  "  return resolved;",
  "};",
  "",
].join("\n");
const outputs = new Map([
  ['server/types/languages.ts', languagesSource],
  ['src/i18n/locale/loadLocaleMessages.generated.ts', clientSource],
]);
if (process.argv.includes('--check')) {
  for (const [relative, content] of outputs) {
    const target = path.join(root, relative);
    if (!fs.existsSync(target) || fs.readFileSync(target, 'utf8') !== content) {
      console.error(`${relative} is stale; run pnpm i18n:registry.`);
      process.exitCode = 1;
    }
  }
} else if (process.argv.includes('--write')) {
  for (const [relative, content] of outputs) {
    const target = path.join(root, relative);
    fs.mkdirSync(path.dirname(target), { recursive: true });
    fs.writeFileSync(target, content);
  }
} else {
  throw new Error('Use --write or --check.');
}
