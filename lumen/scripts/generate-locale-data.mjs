import { access, mkdir, readFile, readdir, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import prettier from 'prettier';

const lumen = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const repo = path.resolve(lumen, '..');
const configPath = path.join(repo, 'config/i18n/locales.json');
const keyPath = path.join(lumen, 'i18n-keys.json');
const overridesPath = path.join(lumen, 'i18n-overrides.json');
const destination = path.join(lumen, 'src/i18n/localeData.generated.ts');
const catalogsDestination = path.join(lumen, 'src/i18n/locales');
try {
  await access(configPath);
} catch {
  // The production image is built with lumen/ as its Docker context. In that
  // isolated context, use the checked-in generated catalog produced from the
  // native locale sources by the repository-level build.
  await access(destination);
  process.exit(0);
}

const config = JSON.parse(await readFile(configPath, 'utf8'));
const keys = JSON.parse(await readFile(keyPath, 'utf8'));
const overrides = JSON.parse(await readFile(overridesPath, 'utf8'));
const readCatalog = async (file) =>
  JSON.parse(await readFile(path.join(repo, 'src/i18n/locale', file), 'utf8'));

async function listTypeScriptFiles(directory) {
  const entries = await readdir(directory, { withFileTypes: true });
  const groups = await Promise.all(
    entries.map((entry) => {
      const file = path.join(directory, entry.name);
      return entry.isDirectory()
        ? listTypeScriptFiles(file)
        : /\.tsx?$/.test(entry.name)
          ? [file]
          : [];
    })
  );
  return groups.flat();
}

const staticKeys = new Set(keys);
const missingStaticKeys = [];
for (const file of await listTypeScriptFiles(path.join(lumen, 'src'))) {
  const source = await readFile(file, 'utf8');
  for (const match of source.matchAll(/\bt\s*\(\s*(['"])([^'"]+)\1/g)) {
    if (!staticKeys.has(match[2]))
      missingStaticKeys.push(`${path.relative(repo, file)}: ${match[2]}`);
  }
}
if (missingStaticKeys.length)
  throw new Error(
    `Static Lumen translation keys are missing from lumen/i18n-keys.json:\n${missingStaticKeys.join('\n')}`
  );

const english = await readCatalog(
  config.locales.find(({ tag }) => tag === config.baseLocale).clientFile
);

for (const key of keys) {
  const hasLocaleOverride = Object.values(overrides).some(
    (messages) => typeof messages?.[key] === 'string'
  );
  if (typeof english[key] !== 'string' && !hasLocaleOverride)
    throw new Error(`Missing English message ${key} in the native catalog.`);
}
for (const [tag, messages] of Object.entries(overrides)) {
  if (!config.locales.some((locale) => locale.tag === tag))
    throw new Error(`Unknown locale ${tag} in Lumen translation overrides.`);
  for (const [key, message] of Object.entries(messages)) {
    if (!keys.includes(key))
      throw new Error(
        `Override message ${key} is not listed in i18n-keys.json.`
      );
    if (typeof message !== 'string' || !message)
      throw new Error(`Invalid ${tag} override message ${key}.`);
  }
}

const entries = [];
const catalogs = [];
for (const locale of config.locales) {
  const chain = [];
  const seen = new Set();
  let current = locale;
  while (current && !seen.has(current.tag)) {
    seen.add(current.tag);
    chain.unshift(current);
    current = config.locales.find(
      ({ tag }) => tag === (current.fallback || config.baseLocale)
    );
  }
  // The runtime resolves missing locale entries from the English dictionary.
  // Keep that base catalog in one place instead of repeating it per locale.
  const effectiveChain =
    locale.tag === config.baseLocale
      ? chain
      : chain.filter(({ tag }) => tag !== config.baseLocale);
  const catalog = {};
  for (const item of effectiveChain) {
    const source = await readCatalog(item.clientFile);
    for (const key of keys) {
      if (typeof source[key] === 'string' && source[key])
        catalog[key] = source[key];
    }
  }
  for (const item of effectiveChain) {
    for (const key of keys) {
      const message = overrides[item.tag]?.[key];
      if (typeof message === 'string' && message) catalog[key] = message;
    }
  }
  entries.push({
    tag: locale.tag,
    nativeName: locale.nativeName,
    direction: locale.direction,
  });
  catalogs.push({ tag: locale.tag, messages: catalog });
}

await mkdir(catalogsDestination, { recursive: true });
for (const { tag, messages } of catalogs) {
  const catalogPath = path.join(catalogsDestination, `${tag}.generated.ts`);
  const serializedMessages = JSON.stringify(messages, null, 2)
    .replaceAll('\u2068', '\\u2068')
    .replaceAll('\u2069', '\\u2069');
  const catalogOutput = await prettier.format(
    `// Generated by lumen/scripts/generate-locale-data.mjs. Do not edit.\nexport const messages = ${serializedMessages} as const;\n`,
    {
      ...(await prettier.resolveConfig(catalogPath)),
      filepath: catalogPath,
    }
  );
  await writeFile(catalogPath, catalogOutput);
}

const loaders = Object.fromEntries(
  entries
    .filter(({ tag }) => tag !== config.baseLocale)
    .map(({ tag }) => [tag, `() => import('./locales/${tag}.generated')`])
);
const output = await prettier.format(
  `// Generated by lumen/scripts/generate-locale-data.mjs. Do not edit.\nexport const localeMetadata = ${JSON.stringify(entries, null, 2)} as const;\nexport const localeLoaders = {\n${Object.entries(
    loaders
  )
    .map(([tag, loader]) => `  ${JSON.stringify(tag)}: ${loader},`)
    .join('\n')}\n} as const;\n`,
  {
    ...(await prettier.resolveConfig(destination)),
    filepath: destination,
  }
);
await mkdir(path.dirname(destination), { recursive: true });
await writeFile(destination, output);
