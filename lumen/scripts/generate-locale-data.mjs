import { mkdir, readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const lumen = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const repo = path.resolve(lumen, '..');
const configPath = path.join(repo, 'config/i18n/locales.json');
const keyPath = path.join(lumen, 'i18n-keys.json');
const config = JSON.parse(await readFile(configPath, 'utf8'));
const keys = JSON.parse(await readFile(keyPath, 'utf8'));
const readCatalog = async (file) =>
  JSON.parse(await readFile(path.join(repo, 'src/i18n/locale', file), 'utf8'));
const english = await readCatalog(
  config.locales.find(({ tag }) => tag === config.baseLocale).clientFile
);

for (const key of keys) {
  if (typeof english[key] !== 'string')
    throw new Error(`Missing English message ${key} in the native catalog.`);
}

const entries = [];
for (const locale of config.locales) {
  const chain = [];
  const seen = new Set();
  let current = locale;
  while (current && !seen.has(current.tag)) {
    seen.add(current.tag);
    chain.unshift(current);
    current = config.locales.find(
      ({ tag }) => tag === (current.fallback || config.baseLocale)
    );
  }
  const catalog = {};
  for (const item of chain) {
    const source = await readCatalog(item.clientFile);
    for (const key of keys) {
      if (typeof source[key] === 'string' && source[key])
        catalog[key] = source[key];
    }
  }
  entries.push({
    tag: locale.tag,
    nativeName: locale.nativeName,
    direction: locale.direction,
    messages: catalog,
  });
}

const output = `// Generated by lumen/scripts/generate-locale-data.mjs. Do not edit.\nexport const localeData = ${JSON.stringify(entries, null, 2)} as const;\n`;
const destination = path.join(lumen, 'src/i18n/localeData.generated.ts');
await mkdir(path.dirname(destination), { recursive: true });
await writeFile(destination, output);
