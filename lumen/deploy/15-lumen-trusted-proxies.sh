#!/bin/sh
# Writes /tmp/lumen/conf.d/00-lumen-trusted-proxies.conf from LUMEN_TRUSTED_PROXIES before nginx
# starts. Forwarding headers (X-Forwarded-For, CF-Connecting-IP, X-Forwarded-Proto) are believed
# only when the connection comes from one of these addresses. With none set, every visitor is the
# address that connected, so nobody can pick the IP SeerrNG sees (its sign-in rate limit is per IP).
#   LUMEN_TRUSTED_PROXIES  addresses/CIDRs of the reverse proxy or tunnel in front of Lumen,
#                          comma or space separated, e.g. "172.17.0.0/16" or "10.0.0.5, fd00::/8"
#   LUMEN_REAL_IP_HEADER   header that proxy puts the visitor in: X-Forwarded-For (default) or
#                          CF-Connecting-IP
set -eu
set -f

# under /tmp so any unprivileged user can run the image (see the Dockerfile)
conf="${NGINX_ENVSUBST_OUTPUT_DIR:-/tmp/lumen/conf.d}"
mkdir -p "$conf"
out="$conf/00-lumen-trusted-proxies.conf"
header="${LUMEN_REAL_IP_HEADER:-X-Forwarded-For}"
proxies=$(printf '%s' "${LUMEN_TRUSTED_PROXIES:-}" | tr ',' ' ')

case "$header" in
  X-Forwarded-For | CF-Connecting-IP | X-Real-IP) ;;
  *)
    echo "lumen: LUMEN_REAL_IP_HEADER must be X-Forwarded-For, CF-Connecting-IP or X-Real-IP" >&2
    exit 1
    ;;
esac

realip=""
geo=""
for p in $proxies; do
  case "$p" in
    *[!0-9A-Fa-f.:/]* | "")
      echo "lumen: '$p' in LUMEN_TRUSTED_PROXIES is not an address or CIDR" >&2
      exit 1
      ;;
  esac
  realip="${realip}set_real_ip_from $p;
"
  geo="${geo}  $p 1;
"
done

{
  echo "# generated by 15-lumen-trusted-proxies.sh"
  if [ -n "$realip" ]; then
    printf '%s' "$realip"
    echo "real_ip_header $header;"
    echo "real_ip_recursive on;"
  fi
  # 1 when the connection itself came from a trusted proxy (before realip rewrote the address)
  echo 'geo $realip_remote_addr $lumen_via_proxy {'
  echo '  default 0;'
  printf '%s' "$geo"
  echo '}'
} >"$out"

if [ -n "$realip" ]; then
  echo "lumen: trusting $header from: $proxies"
else
  echo "lumen: no trusted proxies; client forwarding headers are ignored"
fi
