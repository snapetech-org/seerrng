// ComicVine says nothing about a volume's language, but its publisher does:
// Norma publishes in Spanish, Egmont Manga in German, Haksan in Korean. This
// table maps publisher names (as ComicVine spells them) to an ISO 639-1
// language, so editions of one work can be told apart and the English one
// recommended. Names are compared after normalizeName(); a publisher that
// isn't listed has an unknown language.

const normalizeName = (name: string): string =>
  name
    .normalize('NFKD')
    .replace(/[̀-ͯ]/g, '')
    .toLowerCase()
    .replace(/&/g, ' and ')
    .replace(/[^\p{L}\p{N}]+/gu, ' ')
    .trim();

