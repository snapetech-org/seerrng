const LANGUAGE_BY_PUBLISHER = new Map<string, string>();
for (const name of WESTERN_ENGLISH) LANGUAGE_BY_PUBLISHER.set(name, 'en');
for (const [language, names] of Object.entries(BY_LANGUAGE)) {
  for (const name of names) {
    LANGUAGE_BY_PUBLISHER.set(normalizeName(name), language);
  }
}
const WESTERN = new Set(WESTERN_ENGLISH);

/**
 * The language a publisher's volumes are in, or undefined when the publisher
 * isn't known. English and Japanese manga publishers come from the manga
 * publisher list.
 */
export const publisherLanguage = (name?: string | null): string | undefined => {
  if (!name) return undefined;
  if (isEnglishMangaPublisher(name)) return 'en';
  if (isJapaneseMangaPublisher(name)) return 'ja';
  const n = normalizeName(name);
  const exact = LANGUAGE_BY_PUBLISHER.get(n);
  if (exact) return exact;
  // "Panini Comics (Germany)" style names: a known country word settles it
  if (/\b(deutschland|germany|verlag)\b/.test(n)) return 'de';
  if (/\b(france|editions?)\b/.test(n)) return 'fr';
  if (/\b(espana|spain|mexico|argentina|editorial|ediciones)\b/.test(n))
    return 'es';
  if (/\b(italia|italy|edizioni)\b/.test(n)) return 'it';
  if (/\b(brasil|brazil|portugal|editora)\b/.test(n)) return 'pt';
  if (/\b(polska|poland)\b/.test(n)) return 'pl';
  if (/\b(nxb|nha xuat ban)\b/.test(n)) return 'vi';
  return undefined;
};

export const languageName = (code?: string): string | undefined =>
  code ? (LANGUAGE_NAMES[code] ?? code.toUpperCase()) : undefined;

/** A Western English-language comic publisher (Marvel, DC, Image…). */
export const isWesternEnglishPublisher = (name?: string | null): boolean =>
  !!name && WESTERN.has(normalizeName(name));

